#!/usr/bin/env python3
"""Reads the buff bitmaps (digits, bears, oil, smoothie) out of Natro's Walk.ahk and writes
swift/Sources/HiveMacCore/BuffTemplates.swift with raw RGB pixel rows. No PIL needed.
usage: extract_natro_buffs.py <Walk.ahk> <out.swift>"""
import base64, re, struct, sys, zlib

def decode_png(data):
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    pos, idat, plte, trns = 8, b"", None, None
    while pos < len(data):
        n, typ = struct.unpack(">I4s", data[pos:pos+8]); body = data[pos+8:pos+8+n]; pos += 12 + n
        if typ == b"IHDR": w, h, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", body)
        elif typ == b"PLTE": plte = body
        elif typ == b"tRNS": trns = body
        elif typ == b"IDAT": idat += body
    assert interlace == 0
    chans = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype]
    bpp = max(1, chans * depth // 8); stride = (w * chans * depth + 7) // 8
    raw = zlib.decompress(idat); rows = []; prev = bytearray(stride); p = 0
    for _ in range(h):
        f = raw[p]; line = bytearray(raw[p+1:p+1+stride]); p += 1 + stride
        for i in range(stride):
            a = line[i-bpp] if i >= bpp else 0; b = prev[i]; c = prev[i-bpp] if i >= bpp else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pr = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[i] = (line[i] + pr) & 255
        rows.append(line); prev = line
    def samples(line):
        if depth == 8: return list(line)
        out = []
        for byte in line:
            for k in range(8 // depth): out.append((byte >> (8 - depth * (k + 1))) & ((1 << depth) - 1))
        return out
    px = []
    for line in rows:
        s = samples(line)
        for x in range(w):
            if ctype == 2: px += s[x*3:x*3+3]
            elif ctype == 6: px += s[x*4:x*4+3]
            elif ctype == 0:
                v = s[x] * 255 // ((1 << depth) - 1); px += [v, v, v]
            elif ctype == 4: px += [s[x*2]] * 3
            else: i = s[x]; px += list(plte[i*3:i*3+3])
    return w, h, px

src = open(sys.argv[1]).read()
items = []
for m in re.finditer(r'(buff_characters\[(\d)\]|bitmaps\["pBM(Oil|Smoothie|Bear\w+)"\])\s*:=\s*Gdip_BitmapFromBase64\("([^"]+)"\)', src):
    name = ("digit" + m.group(2)) if m.group(2) else m.group(3).lower()
    w, h, px = decode_png(base64.b64decode(m.group(4)))
    items.append((name, w, h, px))
out = ["// Generated by scripts/extract_natro_buffs.py from Natro's Walk.ahk (GPL-3.0). Do not edit.", "",
       "enum BuffTemplates {", "    /// name, width, height, RGB bytes",
       "    static let all: [(name: String, w: Int, h: Int, rgb: [UInt8])] = ["]
for name, w, h, px in items:
    out.append(f'        ("{name}", {w}, {h}, [{",".join(map(str, px))}]),')
out += ["    ]", "}", ""]
open(sys.argv[2], "w").write("\n".join(out))
print(len(items), "bitmaps:", [(n, w, h) for n, w, h, _ in items])
